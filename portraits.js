(() => {
  const {choose:L, translate:T} = window.COOKPATH_I18N;
  window.COOKPATH_SHOW_PORTRAIT = quote => {
    const portrait=window.COOKPATH_PORTRAITS[quote.chef];
    if(!portrait)return;
    const image=document.querySelector('#quote-portrait');
    image.src=portrait.image;
    image.style.objectPosition=portrait.position || 'center 28%';
    image.alt=L(`Portrait of ${quote.chef}`,`Πορτρέτο του/της ${T(quote.chef)}`);
    image.dataset.chef=quote.chef;
    const credit=document.querySelector('#quote-photo-credit');
    credit.textContent=L('Photo','Φωτογραφία')+': '+portrait.author;
    credit.href=portrait.source;
    credit.title=portrait.title+' · '+portrait.license+' · '+portrait.adaptation;
    const license=document.querySelector('#quote-photo-license');
    license.hidden=!portrait.licenseUrl;
    license.textContent=portrait.license;
    if(portrait.licenseUrl)license.href=portrait.licenseUrl;
  };
})();
